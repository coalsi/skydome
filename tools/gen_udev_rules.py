#!/usr/bin/env python3
"""Write udev rules that give each camera a stable name tied to its USB port.

    python3 tools/gen_udev_rules.py              # print the rules
    sudo python3 tools/gen_udev_rules.py --install

Reads the id_path entries from config/cameras.yaml (filled in by
identify_cameras.py) and creates /dev/skycam-<name> for each camera's
capture node. Keyed on ID_PATH (the physical port), never /dev/videoN.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RULES_PATH = Path("/etc/udev/rules.d/99-skydome-cameras.rules")


def render(config: Path) -> str:
    data = yaml.safe_load(config.read_text())
    lines = ["# Generated by tools/gen_udev_rules.py from config/cameras.yaml - do not edit by hand",
             "# ATTR{index}==\"0\" picks the capture node; UVC also creates a metadata node."]
    missing = []
    for cam in data["cameras"]:
        if not cam.get("id_path"):
            missing.append(cam["name"])
            continue
        lines.append(f'SUBSYSTEM=="video4linux", ENV{{ID_PATH}}=="{cam["id_path"]}", ATTR{{index}}=="0", '
                     f'SYMLINK+="skycam-{cam["name"]}", GROUP="video", MODE="0660"')
    if missing:
        sys.exit(f"no id_path yet for: {', '.join(missing)} - run tools/identify_cameras.py first")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", type=Path, default=ROOT / "config" / "cameras.yaml")
    ap.add_argument("--install", action="store_true", help=f"write {RULES_PATH} and reload udev")
    args = ap.parse_args()
    rules = render(args.config)
    if not args.install:
        print(rules, end="")
        return
    RULES_PATH.write_text(rules)
    subprocess.run(["udevadm", "control", "--reload-rules"], check=True)
    subprocess.run(["udevadm", "trigger", "--subsystem-match=video4linux"], check=True)
    print(f"Wrote {RULES_PATH}. Check: ls -l /dev/skycam-*")


if __name__ == "__main__":
    main()
